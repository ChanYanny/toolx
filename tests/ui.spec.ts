test('UUID batch settings and text diff are interactive', async ({ page }) => {
  await page.goto('/#uuid');
  await page.getByLabel('生成数量', { exact: true }).fill('3');
  await page.getByLabel('大写字母').check();
  await page.getByRole('button', { name: '生成 UUID', exact: true }).click();
  await expect(page.locator('.uuid-row')).toHaveCount(3);
  const values = await page.locator('.uuid-row code').allTextContents();
  expect(values.every((id) => /^[A-F0-9-]{36}$/.test(id))).toBe(true);
  await page.locator('.quick-nav').getByText('文本对比').click();
  await page.getByRole('button', { name: '载入示例' }).click();
  await page.getByRole('button', { name: '开始对比' }).click();
  await expect(page.locator('.diff-line.added')).toHaveCount(3);
  await expect(page.locator('.diff-line.removed')).toHaveCount(2);
  await page.getByLabel('仅显示差异').check();
  await expect(page.locator('.diff-line')).toHaveCount(5);
});

