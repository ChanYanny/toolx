import { expect, test } from '@playwright/test';

test('catalogue search, favorites, theme persistence, and keyboard navigation', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('.tool-card')).toHaveCount(7);
  await page.screenshot({ path: 'artifacts/home-desktop.png', fullPage: true });
  await page.getByLabel('搜索工具', { exact: true }).fill('base64');
  await expect(page.locator('.tool-card')).toHaveCount(1);
  await page.getByLabel('清空搜索').click();
  await page.getByLabel('收藏JSON 格式化', { exact: true }).click();
  await page.locator('.primary-nav').getByText('我的收藏').click();
  await expect(page.locator('.tool-card')).toHaveCount(1);
  await page.reload();
  await expect(page.locator('.tool-card')).toHaveCount(1);
  const theme = await page.locator('html').getAttribute('data-theme');
  await page.getByLabel('切换深色或浅色主题').click();
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme', theme === 'dark' ? 'light' : 'dark');
  await page.screenshot({ path: 'artifacts/dark-theme.png', fullPage: true });
  await page.keyboard.press('ControlOrMeta+k');
  await page.getByLabel('快速查找工具', { exact: true }).fill('uuid');
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'UUID 生成器', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('JSON precision, clipboard, download, error feedback, and in-memory drafts', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.goto('/#json');
  await page.getByLabel('输入内容').fill('{"id":9223372036854775807,"hello":"你好"}');
  await page.getByRole('button', { name: '格式化 JSON', exact: true }).click();
  await expect(page.locator('.code-output')).toContainText('9223372036854775807');
  await page.getByRole('button', { name: '复制', exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('9223372036854775807');
  const downloadPromise = page.waitForEvent('download');
  await page.getByLabel('下载结果').click();
  expect((await downloadPromise).suggestedFilename()).toBe('toolx.json');
  await page.screenshot({ path: 'artifacts/json-workspace.png', fullPage: true });
  await page.locator('.quick-nav').getByText('Base64 编解码').click();
  await expect(page.getByRole('heading', { name: 'Base64 编解码', exact: true })).toBeVisible();
  await page.locator('.quick-nav').getByText('JSON 格式化').click();
  await expect(page.getByRole('heading', { name: 'JSON 格式化', exact: true })).toBeVisible();
  await expect(page.getByRole('textbox', { name: '输入内容', exact: true })).toHaveValue('{"id":9223372036854775807,"hello":"你好"}');
  await page.getByRole('textbox', { name: '输入内容', exact: true }).fill('{"broken":}');
  await page.getByRole('button', { name: '格式化 JSON', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('JSON 格式有误');
  await expect(page.locator('.code-output:visible')).toHaveCount(0);
});

test('JSON escaping, unescaping, and result refill preserve source text', async ({ page }) => {
  await page.goto('/#json');
  const source = '{\n  "name": "你好 👋",\n  "id": 9223372036854775807\n}';
  const input = page.getByRole('textbox', { name: '输入内容', exact: true });
  await input.fill(source);
  await page.getByRole('button', { name: '转义', exact: true }).click();
  await expect(page.locator('.code-output')).toHaveText(JSON.stringify(source));
  await expect(page.locator('.panel-subtitle').last()).toHaveText('已转义 · JSON 字符串');
  await page.getByRole('button', { name: '回填输入', exact: true }).click();
  await expect(input).toHaveValue(JSON.stringify(source));
  await page.getByRole('button', { name: '去转义', exact: true }).click();
  expect(await page.locator('.code-output').textContent()).toBe(source);
  await page.getByRole('button', { name: '回填输入', exact: true }).click();
  await page.getByRole('button', { name: '格式化 JSON', exact: true }).click();
  await expect(page.locator('.code-output')).toContainText('9223372036854775807');
  await input.fill(String.raw`{\"name\":\"ToolX\"}`);
  await page.getByRole('button', { name: '去转义', exact: true }).click();
  await expect(page.locator('.code-output')).toHaveText('{"name":"ToolX"}');
  await input.fill(String.raw`"\x41"`);
  await page.getByRole('button', { name: '去转义', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('无法去转义');
  await expect(page.locator('.code-output')).toHaveCount(0);
});

test('shared dropdowns support mouse, keyboard, themes, and conversion settings', async ({ page }) => {
  await page.goto('/#json');
  const indent = page.getByRole('combobox', { name: 'JSON 缩进', exact: true });
  await indent.click();
  await expect(page.getByRole('listbox')).toBeVisible();
  await page.screenshot({ path: 'artifacts/json-dropdown-light.png' });
  await page.getByRole('option', { name: '4 个空格', exact: true }).click();
  await page.getByRole('textbox', { name: '输入内容', exact: true }).fill('{"a":1}');
  await page.getByRole('button', { name: '格式化 JSON', exact: true }).click();
  expect(await page.locator('.code-output').textContent()).toBe('{\n    "a": 1\n}');
  await indent.focus();
  await page.keyboard.press('Space');
  await expect(page.getByRole('option', { name: '4 个空格', exact: true })).toBeFocused();
  await page.keyboard.press('End');
  await expect(page.getByRole('option', { name: 'Tab 制表符', exact: true })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(indent).toHaveText('Tab 制表符');
  await page.getByRole('button', { name: '格式化 JSON', exact: true }).click();
  expect(await page.locator('.code-output').textContent()).toBe('{\n\t"a": 1\n}');
  await page.getByLabel('切换深色或浅色主题').click();
  await indent.click();
  await expect(page.getByRole('listbox')).toBeVisible();
  await page.screenshot({ path: 'artifacts/json-dropdown-dark.png' });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('listbox')).toHaveCount(0);
  await expect(indent).toBeFocused();
  await page.locator('.quick-nav').getByText('URL 编解码').click();
  await expect(page.getByRole('heading', { name: 'URL 编解码', exact: true })).toBeVisible();
  const urlMode = page.getByRole('combobox', { name: 'URL 转换模式', exact: true });
  await urlMode.click();
  await page.getByRole('option', { name: /完整 URL/ }).click();
  await page.getByRole('textbox', { name: '输入内容', exact: true }).fill('https://example.com/?q=你好');
  await page.getByRole('button', { name: '开始编码', exact: true }).click();
  await expect(page.locator('.code-output:visible')).toHaveText('https://example.com/?q=%E4%BD%A0%E5%A5%BD');
  await page.locator('.quick-nav').getByText('时间戳转换').click();
  await page.getByRole('combobox', { name: '时间戳单位', exact: true }).click();
  await page.getByRole('option', { name: '毫秒 (ms)', exact: true }).click();
  await page.getByLabel('Unix 时间戳', { exact: true }).fill('1700000000000');
  await page.getByRole('button', { name: '转换为日期' }).click();
  await expect(page.locator('.result-list:visible')).toContainText('2023-11-14T22:13:20.000Z');
});

