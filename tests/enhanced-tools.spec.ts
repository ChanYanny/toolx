import { expect, test } from '@playwright/test';

test('JSON tree folding, search, copy paths, queries and precision work together', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.goto('/#json');
  await page.getByLabel('输入内容', { exact: true }).fill('{"items":[{"id":9223372036854775807,"a.b":"你好"}],"isLosslessNumber":true,"__proto__":{"ok":true}}');
  await page.getByRole('button', { name: '树形', exact: true }).click();
  await expect(page.locator('.json-tree')).toContainText('items');
  await page.getByRole('button', { name: '全部折叠', exact: true }).click();
  await expect(page.locator('.json-node')).toHaveCount(1);
  await page.getByRole('button', { name: '全部展开', exact: true }).click();
  await expect(page.locator('.json-tree')).toContainText('9223372036854775807');
  const path = '$.items[0]["a.b"]';
  await page.getByRole('button', { name: `复制路径 ${path}`, exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(path);
  await page.getByLabel('搜索 JSON 节点').fill('你好');
  await expect(page.locator('.json-node.is-match')).toHaveCount(1);
  await expect(page.locator('.json-node')).toHaveCount(4);
  await page.screenshot({ path: 'artifacts/json-tree-search.png', fullPage: true });
  await page.getByRole('button', { name: 'JSONPath', exact: true }).click();
  const query = page.getByLabel('JSONPath 表达式');
  await query.fill('$..id');
  await query.press('Enter');
  await expect(page.locator('.query-result .code-output')).toHaveText('[\n9223372036854775807\n]');
  await page.getByRole('button', { name: '复制查询结果', exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('[\n9223372036854775807\n]');
  const download = page.waitForEvent('download');
  await page.getByLabel('下载查询结果', { exact: true }).click();
  expect((await download).suggestedFilename()).toBe('jsonpath-results.json');
  await query.fill('$[?(@.x)]');
  await query.press('Enter');
  await expect(page.getByRole('alert')).toContainText('暂不支持');
  await expect(page.locator('.query-result')).toHaveCount(0);
  await query.fill(path);
  await query.press('Enter');
  await expect(page.locator('.query-result .code-output')).toContainText('"你好"');
  await page.getByRole('button', { name: '转义', exact: true }).click();
  await expect(page.getByRole('button', { name: '文本', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByLabel('输入内容', { exact: true }).fill('{"changed":true}');
  await expect(page.locator('.code-output')).toHaveCount(0);
  await page.getByRole('button', { name: '树形', exact: true }).click();
  await expect(page.locator('.json-tree')).toContainText('changed');
  await expect(page.locator('.json-tree')).not.toContainText('items');
});

test('regex live highlights, captures, examples, replacement and invalid syntax', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.goto('/#regex');
  await expect(page.locator('.regex-status')).toContainText('2 处匹配');
  await page.getByRole('combobox', { name: '正则示例', exact: true }).click();
  await page.getByRole('option', { name: '日期重排', exact: true }).click();
  await expect(page.locator('.regex-replace > .code-output')).toContainText('28/09/2026');
  await expect(page.locator('.capture-list')).toContainText('$<year>');
  await page.getByRole('button', { name: '查看第 2 处匹配', exact: true }).click();
  await expect(page.getByLabel('查看第几处匹配')).toHaveValue('2');
  await expect(page.locator('.capture-list')).toContainText('2026-10-01');
  await page.getByRole('button', { name: '复制替换结果', exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('01/10/2026');
  await page.screenshot({ path: 'artifacts/regex-desktop.png', fullPage: true });
  await page.getByLabel('g 全局', { exact: true }).uncheck();
  await expect(page.locator('.regex-highlight mark')).toHaveCount(1);
  await expect(page.locator('.regex-replace > .code-output')).toContainText('2026-10-01');
  await page.getByLabel('正则表达式', { exact: true }).fill('[');
  await expect(page.getByRole('alert')).toContainText('表达式无法执行');
  await expect(page.getByRole('button', { name: '复制替换结果', exact: true })).toBeDisabled();
});

test('regex timeout can recover, zero-width Unicode is safe, and partial replacements are disabled', async ({ page }) => {
  await page.goto('/#regex');
  const pattern = page.getByLabel('正则表达式', { exact: true });
  const input = page.getByLabel('正则测试文本', { exact: true });
  await pattern.fill('(a+)+$');
  await input.fill(`${'a'.repeat(50)}!`);
  await expect(page.getByRole('alert')).toContainText('匹配超时', { timeout: 6000 });
  await pattern.fill('(?:)');
  await input.fill('😀a');
  await page.getByLabel('u Unicode', { exact: true }).check();
  await page.getByLabel('替换模板', { exact: true }).fill('_');
  await expect(page.locator('.regex-status')).toContainText('3 处匹配');
  await expect(page.locator('.regex-highlight .zero-width')).toHaveCount(3);
  await expect(page.locator('.regex-replace > .code-output')).toHaveText('_😀_a_');
  await pattern.fill('a');
  await input.fill('a'.repeat(2001));
  await expect(page.locator('.tool-notice')).toContainText('仅展示前 2000');
  await expect(page.getByRole('button', { name: '复制替换结果', exact: true })).toBeDisabled();
  await pattern.fill('b');
  await input.fill('b');
  await expect(page.locator('.regex-status')).toContainText('1 处匹配');
  await expect(page.locator('.regex-highlight mark')).toHaveText('b');
});

