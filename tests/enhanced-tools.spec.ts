test('all seven favorites survive reloading preferences', async ({ page }) => {
  await page.goto('/?view=sidepanel');
  for (const button of await page.locator('.sidepanel-tool .favorite').all()) await button.click();
  await page.reload();
  await page.getByRole('button', { name: '收藏 7', exact: true }).click();
  await expect(page.locator('.sidepanel-tool')).toHaveCount(7);
  await page.getByLabel('搜索工具', { exact: true }).fill('正则');
  await expect(page.locator('.sidepanel-tool')).toHaveCount(1);
});
